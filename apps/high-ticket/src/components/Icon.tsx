/** Message de conclusion d'un outil : l'icône et le libellé portent le sens, pas seulement la couleur. */
export function Verdict({ tone, children }: { tone: "good" | "warn" | "bad"; children: ReactNode }) {
  return (
    <p className={`verdict ${tone}`} role="status">
      <Icon name={tone} size={20} />
      <span>{children}</span>
    </p>
  );
}
